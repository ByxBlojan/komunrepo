function tillInventarie(rad: Rad): Inventarie {
  const avdelning = AVDELNINGAR.find((a) => a.id === rad.avd)!;
  const status = rad.status ?? "tillganglig";

  return {
    id: rad.id,
    namn: rad.namn,
    underkategoriId: rad.under,
    beskrivning: rad.beskrivning,
    skick: rad.skick,
    matt: rad.matt,
    antal: rad.antal,
    inkopsar: rad.ar,
    uppskattatVarde: rad.varde,
    placering: { avdelningId: rad.avd, adress: avdelning.adress, rum: rad.rum },
    status,
    agandeAvdelningId: rad.avd,
    historik: [
      {
        datum: "2026-08-20",
        typ: "registrerad",
        avdelningId: rad.avd,
        kommentar: "Registrerad vid inventering.",
      },
      ...(status === "tillganglig"
        ? [
            {
              datum: "2026-08-21",
              typ: "publicerad" as const,
              avdelningId: rad.avd,
              kommentar: "Publicerad för internt övertagande.",
            },
          ]
        : []),
    ],
  };
}

